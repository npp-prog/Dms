import { useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { useAuth } from '../context/AuthContext.jsx';
import { listDocumentTypes } from '../lib/api.js';

export default function Formats() {
  const { isAdmin } = useAuth();
  const [types, setTypes] = useState(null);
  const [search, setSearch] = useState('');
  const [error, setError] = useState('');

  useEffect(() => {
    listDocumentTypes({ activeOnly: !isAdmin }).then(setTypes).catch((e) => setError(e.message));
  }, [isAdmin]);

  const groups = useMemo(() => {
    const q = search.toLowerCase();
    const filtered = (types || []).filter((t) => `${t.code} ${t.name} ${t.category} ${t.description}`.toLowerCase().includes(q));
    return filtered.reduce((acc, t) => {
      (acc[t.category || 'Uncategorized'] ||= []).push(t);
      return acc;
    }, {});
  }, [types, search]);

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h1>Document Formats</h1>
          <p className="muted">Official formats for forms not generated by PMS, IMS, CBO, CFMS or other LGU systems.</p>
        </div>
        <input className="search" placeholder="Search formats…" value={search} onChange={(e) => setSearch(e.target.value)} />
      </div>
      {error && <div className="alert">{error}</div>}
      {!types && !error && <div className="spinner" />}
      {types && Object.keys(groups).length === 0 && <p className="muted">No formats found.</p>}
      {Object.entries(groups).sort().map(([category, list]) => (
        <section key={category}>
          <h3 className="section-title">{category}</h3>
          <div className="format-grid">
            {list.map((t) => (
              <div key={t.id} className={`card format-card ${t.active === false ? 'inactive' : ''}`}>
                <div className="format-code">{t.code}</div>
                <h4>{t.name}</h4>
                <p className="muted small">{t.description}</p>
                <div className="small muted">
                  {(t.steps || []).length} steps · {(t.checklist || []).length} checklist items · v{t.version || 1}
                  {t.active === false && ' · inactive'}
                </div>
                <div className="row gap">
                  <Link className="btn btn-ghost btn-sm" to={`/formats/${t.id}`}>View format</Link>
                  {t.active !== false && <Link className="btn btn-primary btn-sm" to={`/new/${t.id}`}>Prepare</Link>}
                </div>
              </div>
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}
